/*
 * 문제: 백준 15726 - 이칙연산
 *
 * 문제 내용:
 * 세 수 A, B, C가 주어진다.
 * 세 수의 순서는 바꿀 수 없고, 곱하기(*) 한 번과 나누기(/) 한 번을
 * 반드시 사용하여 얻을 수 있는 가장 큰 값을 구하라.
 * 나눗셈은 소수점 이하를 버린다.
 *
 * 풀이 계획:
 * - A, B, C 순서가 고정이므로 연산자 배치는 2가지 경우만 존재한다.
 *   1) A * B / C
 *   2) A / B * C
 * - 두 경우를 모두 계산하여 최댓값을 출력한다.
 *
 * 시간복잡도: O(1)
 * - 고정된 2가지 경우만 계산하므로 입력 크기에 관계없이 상수 시간이다.
 *
 * 알고리즘: 완전탐색 (Brute Force)
 * - 가능한 모든 연산자 배치(2가지)를 전부 시도하여 최댓값을 구한다.
 */
fun main() {
    // readLine()!!: 표준 입력에서 한 줄을 읽음. null이 아님을 단언(!!)
    // split(" "): 공백 기준으로 문자열을 분리하여 List<String> 반환
    // map { it.toLong() }: 각 문자열을 Long으로 변환 (A, B, C가 최대 10^9이므로 곱셈 시 Long 필요)
    // 구조 분해 선언: val (a, b, c)로 리스트의 원소를 각 변수에 할당
    val (a, b, c) = readLine()!!.split(" ").map { it.toLong() }

    // 경우 1: A * B / C
    // 곱셈을 먼저 수행하므로 Long 범위 내에서 정밀도 손실 없이 정수 나눗셈 가능
    val case1 = a * b / c

    // 경우 2: A / B * C
    // 나눗셈이 먼저이므로 정수 나눗셈 시 정밀도 손실 발생 가능
    // toDouble(): Long을 Double로 변환하여 실수 나눗셈 수행
    // toLong(): 소수점 이하를 버림 (문제 조건)
    val case2 = (a.toDouble() / b * c).toLong()

    // maxOf(): 두 값 중 큰 값을 반환하는 코틀린 표준 라이브러리 함수
    // println(): 결과를 출력하고 줄바꿈
    println(maxOf(case1, case2))
}
