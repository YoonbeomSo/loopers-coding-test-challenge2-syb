/*
 * 문제: 코끼리 (백준 34760)
 *
 * 건국대학교에 코끼리 15마리가 살고 있다. i번째 코끼리 코의 길이는 A_i이다.
 * 1번째부터 15번째까지 순서대로 돌진한다.
 * 쿠는 길이가 정수인 당근 한 개로 길을 막으려 한다.
 *
 * 코끼리의 행동:
 *   - 당근 길이 < 코 길이: 당근을 먹어 치우고 계속 돌진 (당근 소멸, 멈추지 않음)
 *   - 당근 길이 == 코 길이: 당근을 먹어 치우고 잠에 듦 (당근 소멸, 멈춤)
 *   - 당근 길이 > 코 길이: 겁먹고 기절 (당근 유지, 멈춤)
 *   - 당근이 없으면 계속 돌진
 *
 * 모든 코끼리의 돌진을 멈추기 위한 당근의 최소 길이를 구하라.
 *
 * 계획:
 *   1. 당근 길이 L에 대해 코끼리를 순서대로 처리한다.
 *   2. L > A_i이면 코끼리가 기절하고 당근은 그대로 남는다.
 *   3. L == A_i이면 코끼리가 잠들지만 당근이 사라진다.
 *      이후 코끼리들은 당근 없이 계속 돌진하므로 멈출 수 없다.
 *   4. L < A_i이면 코끼리가 당근을 먹고 계속 돌진한다. 실패.
 *
 *   따라서 모든 코끼리를 멈추려면:
 *     - 경우 1: L > 모든 A_i → 전부 기절. 최소 L = max(A_i) + 1
 *     - 경우 2: 15번째 코끼리의 코 길이가 1~14번째보다 엄격히 크면,
 *       L = A_15로 설정 시 1~14번째는 전부 기절(L > A_i), 15번째는 잠듦(L == A_15).
 *       이 경우 최소 L = A_15
 *
 *   정리: A_15 > max(A_1..A_14)이면 답은 A_15, 아니면 답은 max(A_1..A_15) + 1
 *
 * 시간복잡도: O(N) (N=15로 고정)
 *   - 15개의 정수에서 최댓값을 구하는 것이 전부이므로 O(15) = O(1).
 *   - 입력 크기가 상수로 고정되어 있어 어떤 입력이든 즉시 처리 가능.
 */

fun main() {
    // readLine()!!: 표준 입력에서 한 줄을 읽음. !!는 null이 아님을 단언 (String? -> String)
    // trim(): 양쪽 공백 제거
    // split(" "): 공백 기준으로 문자열을 분리하여 List<String> 반환
    // map { it.toInt() }: 각 요소를 Int로 변환하여 List<Int> 반환
    val a = readLine()!!.trim().split(" ").map { it.toInt() }

    // subList(0, 14): 인덱스 0부터 13까지(0-indexed), 즉 코끼리 1~14번의 코 길이
    // max(): 리스트에서 최댓값 반환 (코틀린 컬렉션 확장 함수)
    val maxFirst14 = a.subList(0, 14).max()

    // a[14]: 0-indexed이므로 15번째 코끼리의 코 길이
    // [그리디 알고리즘]
    // 15번째 코끼리가 1~14번째 모두보다 코가 길면,
    // 당근 길이를 A_15로 설정하여 1~14번은 기절, 15번은 잠들게 할 수 있다.
    // 그렇지 않으면 모든 코끼리를 기절시켜야 하므로 max + 1이 필요하다.
    if (a[14] > maxFirst14) {
        // 15번째가 가장 크므로 L = A_15: 1~14번 기절, 15번 잠듦
        println(a[14])
    } else {
        // 모든 코끼리를 기절시켜야 함: L > max(모든 A_i)
        // max(): 전체 리스트의 최댓값
        println(a.max() + 1)
    }
}
